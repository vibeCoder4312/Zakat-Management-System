-- V1__schema.sql: Core schema, sequences, constraints, and indexes
-- Zakat & Charity Management System (PostgreSQL 16)

-- User & Authentication
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'ACCOUNTANT', 'VIEWER')),
    is_active     VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),

    created_by    VARCHAR(100),
    created_on    TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by    VARCHAR(100),
    updated_on    TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Master: Classification
CREATE TABLE zk_classification (
    classification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(30) UNIQUE,
    name              VARCHAR(100) NOT NULL UNIQUE,
    fund_type         VARCHAR(10) NOT NULL CHECK (fund_type IN ('ZAKAT', 'SADAQAH')),
    display_order     INT DEFAULT 99,
    is_active         VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_by        VARCHAR(100),
    created_on        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by        VARCHAR(100),
    updated_on        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Master: Beneficiary Category
CREATE TABLE zk_beneficiary_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    is_active   VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_by  VARCHAR(100),
    created_on  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by  VARCHAR(100),
    updated_on  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Master: Source Account
CREATE TABLE zk_source_account (
    source_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL UNIQUE,
    region            VARCHAR(10) NOT NULL DEFAULT 'INDIA' CHECK (region IN ('INDIA', 'DUBAI')),
    is_active         VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_by        VARCHAR(100),
    created_on        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by        VARCHAR(100),
    updated_on        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Master: Agent
CREATE TABLE zk_agent (
    agent_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    agent_type     VARCHAR(10) NOT NULL DEFAULT 'EMPLOYEE' CHECK (agent_type IN ('EMPLOYEE', 'PARTNER')),
    contact_number VARCHAR(30),
    is_active      VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_by     VARCHAR(100),
    created_on     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by     VARCHAR(100),
    updated_on     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Master: Employee
CREATE TABLE zk_employee (
    employee_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    contact_number VARCHAR(30),
    remarks        VARCHAR(400),
    is_active      VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_by     VARCHAR(100),
    created_on     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by     VARCHAR(100),
    updated_on     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Master: School / Institute
CREATE TABLE zk_school (
    school_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL UNIQUE,
    location   VARCHAR(100),
    is_active  VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    created_by VARCHAR(100),
    created_on TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100),
    updated_on TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Assessment (Yearly Zakat Assessment)
CREATE TABLE zk_assessment (
    assessment_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zakat_year             INT NOT NULL UNIQUE,
    zakat_amount           NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (zakat_amount >= 0),
    carry_forward          NUMERIC(18,2) NOT NULL DEFAULT 0,
    net_payable            NUMERIC(18,2) NOT NULL DEFAULT 0,
    status                 VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    remarks                VARCHAR(1000),
    total_allocated_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
    remaining_balance      NUMERIC(18,2) NOT NULL DEFAULT 0,
    created_by             VARCHAR(100),
    created_on             TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by             VARCHAR(100),
    updated_on             TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Beneficiary
CREATE SEQUENCE zk_beneficiary_code_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE zk_beneficiary (
    beneficiary_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_code     VARCHAR(20) UNIQUE,
    name                 VARCHAR(200) NOT NULL,
    contact_number       VARCHAR(50),
    address              VARCHAR(500),
    description          VARCHAR(4000),
    referred_by          VARCHAR(100),
    verification_status  VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (verification_status IN ('PENDING', 'VERIFIED', 'CANCELLED')),
    verified_by          VARCHAR(100),
    verified_on          TIMESTAMPTZ,
    verification_note    VARCHAR(500),
    is_active            VARCHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y', 'N')),
    beneficiary_category VARCHAR(100),
    zakat_year           INT,
    created_by           VARCHAR(100),
    created_on           TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by           VARCHAR(100),
    updated_on           TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_beneficiary_name ON zk_beneficiary(name);
CREATE INDEX idx_beneficiary_ver_stat ON zk_beneficiary(verification_status);
CREATE INDEX idx_beneficiary_is_act ON zk_beneficiary(is_active);

-- Allocation (Financial Distribution Line Items)
CREATE TABLE zk_allocation (
    allocation_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id              BIGINT NOT NULL REFERENCES zk_assessment(assessment_id) ON DELETE RESTRICT,
    classification_id          BIGINT NOT NULL REFERENCES zk_classification(classification_id) ON DELETE RESTRICT,
    beneficiary_id             BIGINT NOT NULL REFERENCES zk_beneficiary(beneficiary_id) ON DELETE RESTRICT,
    planned_amount             NUMERIC(18,2) NOT NULL CHECK (planned_amount >= 0),
    planned_source_account_id  BIGINT REFERENCES zk_source_account(source_account_id) ON DELETE RESTRICT,
    school_id                  BIGINT REFERENCES zk_school(school_id) ON DELETE RESTRICT,
    current_std                VARCHAR(30),
    prev_std_result            VARCHAR(250),
    paid_amount                NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    paid_on                    DATE,
    payment_method             VARCHAR(10) CHECK (payment_method IN ('CASH', 'ONLINE', 'BANK')),
    paid_source_account_id     BIGINT REFERENCES zk_source_account(source_account_id) ON DELETE RESTRICT,
    paid_via_agent_id          BIGINT REFERENCES zk_agent(agent_id) ON DELETE RESTRICT,
    reference_no               VARCHAR(100),
    currency_code              VARCHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency_code IN ('INR', 'AED')),
    foreign_amount             NUMERIC(18,2),
    fx_rate                    NUMERIC(10,4),
    receipt_received           VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (receipt_received IN ('Y', 'N')),
    receipt_file               BYTEA,
    receipt_filename           VARCHAR(255),
    receipt_mimetype           VARCHAR(100),
    status                     VARCHAR(10) NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'PAID', 'CANCELLED')),
    approval_status            VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (approval_status IN ('PENDING', 'APPROVED')),
    category                   VARCHAR(250),
    zakat_year                 INT NOT NULL,
    remarks                    VARCHAR(500),
    -- Historical denormalized display values preserved from Oracle
    classification             VARCHAR(100),
    beneficiary                VARCHAR(200),
    school                     VARCHAR(200),
    paid_source_account        VARCHAR(200),
    paid_via_agent             VARCHAR(200),
    paid_via_employee          VARCHAR(100),
    created_by                 VARCHAR(100),
    created_on                 TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by                 VARCHAR(100),
    updated_on                 TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_allocation_paid_on ON zk_allocation(paid_on);
CREATE INDEX idx_allocation_src_acct ON zk_allocation(paid_source_account_id);
CREATE INDEX idx_allocation_assessment ON zk_allocation(assessment_id);
CREATE INDEX idx_allocation_classification ON zk_allocation(classification_id);
CREATE INDEX idx_allocation_beneficiary ON zk_allocation(beneficiary_id);
CREATE INDEX idx_allocation_zakat_year ON zk_allocation(zakat_year);
CREATE INDEX idx_allocation_status ON zk_allocation(status);
CREATE INDEX idx_allocation_approval_status ON zk_allocation(approval_status);

-- Zakat Planning (Manual Planning Records)
CREATE TABLE zk_planning (
    planning_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zakat_year        INT NOT NULL,
    plan_type         VARCHAR(20) NOT NULL CHECK (plan_type IN ('ZAKAT', 'SADAQAH')),
    category          VARCHAR(250),
    classification_id BIGINT REFERENCES zk_classification(classification_id) ON DELETE RESTRICT,
    planned_amount    NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (planned_amount >= 0),
    remarks           VARCHAR(1000),
    created_by        VARCHAR(100),
    created_on        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by        VARCHAR(100),
    updated_on        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_planning_year ON zk_planning(zakat_year);
